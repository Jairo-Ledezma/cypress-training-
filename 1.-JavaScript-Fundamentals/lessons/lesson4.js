//relational or comparison operator
// > - more than
//< - less than
// >= - more than equal
//<= less than equal

var result = 10 > 5;
console.log(result);

result = 10 < 5;
console.log(result);

result = 10 >= 11;
console.log(result);

result = 10 <= 5;
console.log(result);

//equality operators 

var x = 1

console.log(x == '1') // compares the value left and right this is called lose comparison 
console.log(x === '1') // compares value and data type this is called strict comparison 

