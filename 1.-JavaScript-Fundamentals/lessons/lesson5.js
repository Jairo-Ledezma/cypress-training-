// Logical 'AND'

console.log(
  "AND operator, both values should be true for the expression to be true",
);
console.log("true and true is -> " + (true && true)); // all values have to be TRUE for expression to be true
console.log("true and false is -> " + (true && false));
console.log("false and false is -> " + (false && false));
console.log("false and true is -> " + (false && true));

// Logical 'OR'
console.log("any value should be true for the expression to be true");
console.log("true and true is -> " + (true || true)); // any values should to be TRUE for expression to be true
console.log("true and false is -> " + (true || false));
console.log("false and false is -> " + (false || false));
console.log("false and true is -> " + (false || true));

// Logical Not 

console.log('Not operator')
console.log('!true is equal to -> '+ !true)
console.log('!false is equal to -> ' + !false)
console.log ('6!==10 is ->'+ (6!==10) + ' because it is true that 6 is not equal to ten')
